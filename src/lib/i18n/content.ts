export function localizeArticle(article: NewsArticle, lang: Lang): NewsArticle {
  if (lang !== "mn") return article;
  const content = MN_NEWS_CONTENT[article.id];
  if (!content) return article;
  return {
    ...article,
    title: content.title,
    summary: content.summary,
    body: content.body ?? article.body,
  };
}

